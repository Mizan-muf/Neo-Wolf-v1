#!/usr/bin/env python3
"""Keeps the level pages (docs/levels/levelNN.md) in step with the shipped levels (Phase 8).

Every level page has a "## Map" section with two ``text`` code blocks:

1. the shipped map file ``game/maps/levelNN.map``, byte for byte (comment lines included);
2. the same grid with the level's entities drawn in (the "annotated grid"), generated by
   ``annotated_grid`` from ``game/defs/levelNN.entities.json``.

``check`` reports every page whose blocks differ from the files; DevKit test
``test_level_docs`` runs it on the shipped campaign. After editing a level, regenerate the
annotated grids with:

    python3 -m tools.devkit.level_docs --write     # rewrite the annotated grids in place
    python3 -m tools.devkit.level_docs             # check only (exit 1 on a mismatch)

The shipped-map block is never rewritten automatically: copy the map in by hand, so that a
changed map is a visible edit of the page (and its prose) too.

Standard library only.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

REPO_ROOT = Path(__file__).resolve().parents[2]

# Entity symbols of the annotated grid (documentation only: not valid map tiles).
ENEMY_SYMBOLS = {"guard": "g", "brute": "b", "runner": "n"}
KEY_SYMBOLS = {"red": "r", "blue": "u", "gold": "y"}
LOCK_SYMBOLS = {"red": "1", "blue": "2", "gold": "3"}
# When several entities share a cell, the most important one is drawn.
PRIORITY = {
    "p": 0,
    "1": 1,
    "2": 1,
    "3": 1,
    "d": 1,
    "t": 1,
    "g": 2,
    "b": 2,
    "n": 2,
    "r": 3,
    "u": 3,
    "y": 3,
    "h": 4,
    "a": 4,
    "v": 5,
}

LEGEND = (
    "Legend (documentation only: lower case and digits are not valid map tiles; the shipped "
    "`.map` above has `.` or `D`/`T` there): `p` player start, `g` guard, `b` brute, `n` "
    "runner, `h` health, `a` ammo, `r` / `u` / `y` red / blue / gold key card, `d` unlocked "
    "door, `1` / `2` / `3` red / blue / gold locked door, `t` checkpoint trigger, `v` "
    "decoration (vase); `#` wall, `A` / `B` wall variants, `X` exit switch. Column numbers "
    "run along the top (tens, then units), row numbers down the left."
)

FENCE_RE = re.compile(r"^```text\n(.*?)^```$", re.MULTILINE | re.DOTALL)


def map_grid(map_text: str) -> List[str]:
    """The grid rows of a map file (comment lines and blank lines removed)."""
    return [line for line in map_text.split("\n") if line and not line.startswith(";")]


def symbol_for(entity: Dict) -> Optional[str]:
    kind = entity.get("type")
    if kind == "player":
        return "p"
    if kind == "enemy":
        return ENEMY_SYMBOLS.get(entity.get("variant", "guard"), "g")
    if kind == "pickup":
        pickup = entity.get("kind")
        if pickup == "key":
            return KEY_SYMBOLS.get(entity.get("key", ""), "?")
        return {"health": "h", "ammo": "a"}.get(pickup, "?")
    if kind == "door":
        return LOCK_SYMBOLS.get(entity.get("lock", ""), "d")
    if kind == "trigger":
        return "t"
    if kind == "decoration":
        return "v"
    return None


def entity_cell(entity: Dict) -> Tuple[int, int]:
    if "mapX" in entity and "mapY" in entity:
        return int(entity["mapX"]), int(entity["mapY"])
    return int(float(entity["x"])), int(float(entity["y"]))


def annotated_grid(map_text: str, entities_doc: Dict) -> str:
    """The map grid with entities drawn in, with column and row numbers."""
    rows = [list(row) for row in map_grid(map_text)]
    best: Dict[Tuple[int, int], str] = {}
    for entity in entities_doc.get("entities", []):
        symbol = symbol_for(entity)
        if symbol is None:
            continue
        cell = entity_cell(entity)
        if cell not in best or PRIORITY[symbol] < PRIORITY[best[cell]]:
            best[cell] = symbol
    for (x, y), symbol in best.items():
        if 0 <= y < len(rows) and 0 <= x < len(rows[y]):
            rows[y][x] = symbol
    width = max(len(row) for row in rows)
    margin = " " * 3
    tens = margin + "".join(str(x // 10) if x % 10 == 0 else " " for x in range(width))
    units = margin + "".join(str(x % 10) for x in range(width))
    lines = [tens.rstrip(), units]
    lines += [f"{y:2d} " + "".join(row) for y, row in enumerate(rows)]
    return "\n".join(lines) + "\n"


def campaign_levels(root: Path) -> List[Dict]:
    campaign = json.loads((root / "game" / "defs" / "campaign.json").read_text(encoding="utf-8"))
    return campaign["levels"]


def page_path(root: Path, level_id: str) -> Path:
    return root / "docs" / "levels" / f"{level_id}.md"


def expected_blocks(root: Path, level: Dict) -> Tuple[str, str]:
    map_text = (root / level["map"]).read_text(encoding="utf-8")
    entities = json.loads((root / level["entities"]).read_text(encoding="utf-8"))
    return map_text, annotated_grid(map_text, entities)


def check(root: Path = REPO_ROOT, write: bool = False) -> List[str]:
    """Returns one problem per line (empty: every page matches). With ``write``, rewrites the
    annotated grid (the second ``text`` block of the "## Map" section) of each page."""
    problems: List[str] = []
    for level in campaign_levels(root):
        page = page_path(root, level["id"])
        rel = page.relative_to(root).as_posix()
        if not page.is_file():
            problems.append(f"{rel}: missing")
            continue
        text = page.read_text(encoding="utf-8")
        blocks = list(FENCE_RE.finditer(text))
        map_text, grid = expected_blocks(root, level)
        if len(blocks) < 2:
            problems.append(
                f"{rel}: expected two ```text blocks (the shipped map and the annotated grid), found {len(blocks)}"
            )
            continue
        if blocks[0].group(1) != map_text:
            problems.append(f"{rel}: the first ```text block differs from {level['map']} (copy the file in)")
        if blocks[1].group(1) != grid:
            if write:
                start, end = blocks[1].span(1)
                text = text[:start] + grid + text[end:]
                with open(page, "w", encoding="utf-8", newline="\n") as handle:  # LF on Windows too
                    handle.write(text)
            else:
                problems.append(
                    f"{rel}: the annotated grid is out of date (python3 -m tools.devkit.level_docs --write)"
                )
    return problems


def main(argv: List[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true", help="rewrite out-of-date annotated grids")
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help="project root (default: this repository)")
    args = parser.parse_args(argv)
    problems = check(args.root, write=args.write)
    for problem in problems:
        print(f"Error: {problem}")
    if problems:
        return 1
    print(f"All {len(campaign_levels(args.root))} level pages match their maps and entity files.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
